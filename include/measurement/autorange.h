/*
 * Auto-range PGA для каналу напруги (ТЗ §14–§16).
 *
 * Пороги задані в вольтах БАТАРЕЇ, а не на вході ADC: так таблиця читається
 * без перерахунку і не ламається при зміні дільника. Перерахунок робить
 * setDividerRatio().
 *
 * Гістерезис: вгору перемикаємось на 90% шкали поточного діапазону, вниз —
 * лише коли напруга впала нижче 80% шкали діапазону, що нижче. Між 80% і 90%
 * лежить мертва зона, яка й гасить дребезг 8→4→8 з ТЗ §15.
 */
#pragma once

#include "measurement/ads1115.h"

namespace meas {

class VoltageAutoRange {
public:
    // divider_k — у скільки разів напруга батареї більша за напругу на AIN2
    // (90k/10k → 10.0). Перебудовує таблицю порогів.
    void setDividerRatio(float divider_k);

    ads::Pga pga() const { return steps_[index_].pga; }
    uint8_t  index() const { return index_; }

    // Примусово зафіксувати діапазон, -1 повертає автоматику. Потрібно для
    // §69: ту саму напругу читаємо на різних PGA і бачимо, чи не змінюється
    // результат — тобто чи не вантажить вхід ADS1115 джерело по-різному на
    // різних діапазонах.
    void setOverride(int index);

    // battery_v — щойно виміряна напруга батареї (до калібрування достатньо).
    // saturated — |raw| впритул до 32768 у поточному діапазоні.
    // Повертає true, якщо діапазон змінено і поточна конверсія недійсна (ТЗ §16).
    bool update(float battery_v, bool saturated);

    // Верхня межа вимірювання в поточному стані таблиці, В.
    float maxBatteryVolts() const;

private:
    struct Step {
        ads::Pga pga;
        float    up;      // вище цього — перейти на діапазон вище
        float    down;    // нижче цього — перейти на діапазон нижче
    };

    static constexpr uint8_t kSteps = 5;

    // Від найчутливішого до найгрубішого. FS_6144 не використовуємо свідомо:
    // ADS1115 живиться від 3.3 В і фізично не побачить входу вище живлення,
    // тож ±4.096 В — реальна стеля, і вона дає в 1.5 раза кращу роздільність.
    Step   steps_[kSteps] = {
        {ads::Pga::FS_0256, 0, 0},
        {ads::Pga::FS_0512, 0, 0},
        {ads::Pga::FS_1024, 0, 0},
        {ads::Pga::FS_2048, 0, 0},
        {ads::Pga::FS_4096, 0, 0},
    };
    uint8_t index_ = kSteps - 1;   // старт із найгрубішого: напруга ще невідома
    int8_t  override_ = -1;
    float   divider_k_ = 10.0f;
};

}  // namespace meas
